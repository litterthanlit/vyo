/** The letter this region draws: an explicit A–Z or 0–9, else one from the seed, else A. */
export function letterOf(region, pose) {
  if (typeof region.letter === "string" && /^[A-Z0-9]$/.test(region.letter)) return region.letter;
  if (!pose || pose.identity) return "A";
  return LETTERS[Math.floor(pose.rnd() * LETTERS.length)];
}

function stampLetter(mask, letter, floor, pose) {
  const rows = BITMAP[letter] || BITMAP.A;
  // 0.75 of the floor, so a narrow mark such as P still spans 60% of the sheet.
  const share = pose.identity ? 0.75 : 0.55 + pose.rnd() * 0.25;
  const cell = (share * floor) / rows.length;
  const gw = 8 * cell;
  const gh = rows.length * cell;
  const x0 = (SHEET.width - gw) / 2;
  const y0 = (floor - gh) / 2;
  rows.forEach((bits, y) => {
    for (let x = 0; x < 8; x++) if ((bits >> (7 - x)) & 1) stampRect(mask, x0 + x * cell, y0 + y * cell, x0 + (x + 1) * cell, y0 + (y + 1) * cell);
  });
}

/** Rows filling one scaled letter. */
export function glyphRows(region, parts, opts) {
  const pose = poseOf(region.seed);
  const mask = blankMask(opts.floor);
  stampLetter(mask, letterOf(region, pose), opts.floor, pose);
  return fillMask(mask, region, parts, opts, GLYPH);
}
