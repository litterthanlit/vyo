// Locate `// TAG:BEGIN … // TAG:END`. Offsets: start = BEGIN line start, bodyStart = first char after
// the BEGIN line break, bodyEnd = start of the END line, end = just past the END marker text.
function findBlock(source, tag) {
  const begin = new RegExp(`^[ \\t]*//[ \\t]*${tag}:BEGIN[^\\r\\n]*`, "m").exec(source);
  if (!begin) return null;
  const afterBegin = begin.index + begin[0].length;
  const endRe = new RegExp(`^[ \\t]*//[ \\t]*${tag}:END[^\\r\\n]*`, "gm");
  endRe.lastIndex = afterBegin;
  const end = endRe.exec(source);
  if (!end) throw new Error(`// ${tag}:BEGIN has no matching // ${tag}:END`);
  let bodyStart = afterBegin;
  if (source.startsWith("\r\n", bodyStart)) bodyStart += 2;
  else if (source[bodyStart] === "\n") bodyStart += 1;
  return { start: begin.index, bodyStart, bodyEnd: end.index, end: end.index + end[0].length };
}

// JSON after `const NAME… = ` up to the last `;` of the block. If a trailing comment makes the last `;`
// the wrong cut, earlier `;` are tried in turn; a `;` inside a JSON string is never a valid cut.
function parseConstJson(body, constRe, onError) {
  const m = constRe.exec(body);
  if (!m) throw new Error(onError(null));
  const rest = body.slice(m.index + m[0].length);
  const cuts = [];
  for (let i = rest.length - 1; i >= 0; i--) if (rest[i] === ";") cuts.push(i);
  cuts.push(rest.length);
  let firstError;
  for (const cut of cuts) {
    try {
      return JSON.parse(rest.slice(0, cut));
    } catch (e) {
      firstError ??= e;
    }
  }
  throw new Error(onError(firstError));
}

const PARTS_CONST_RE = /const\s+PARTS\s*:\s*PartSpec\[\]\s*=\s*/;
const WIRING_CONST_RE = /const\s+WIRING\s*:\s*Wiring\s*=\s*/;

/**
 * Parse the PARTS and WIRING blocks of a canvas. A block that is absent gives null (and a null range).
 * Throws a clear error when a block exists but its JSON is invalid.
 */
export function readBlocks(source) {
  const partsRange = findBlock(source, "PARTS");
  const wiringRange = findBlock(source, "WIRING");
  let parts = null;
  let wiring = null;
  if (partsRange) {
    parts = parseConstJson(source.slice(partsRange.bodyStart, partsRange.bodyEnd), PARTS_CONST_RE, (err) =>
      err
        ? `PARTS must be valid JSON: double quotes, no trailing commas, no comments (${err.message})`
        : 'the PARTS block has no "const PARTS: PartSpec[] = " line',
    );
    if (!Array.isArray(parts)) throw new Error("PARTS must be a JSON array of parts");
  }
  if (wiringRange) {
    wiring = parseConstJson(source.slice(wiringRange.bodyStart, wiringRange.bodyEnd), WIRING_CONST_RE, (err) =>
      err
        ? `WIRING is not valid JSON (${err.message}) — re-run: node tools/scan.mjs wire <facts.json> --into <canvas>`
        : 'the WIRING block has no "const WIRING: Wiring = " line',
    );
  }
  return { parts, wiring, partsRange, wiringRange };
}

// Canonical shape: fixed key order, items/size rounded to 3 decimals. Idempotent.
export function normaliseWiring(w) {
  return {
    facts: w.facts,
    parts: w.parts,
    n: w.n.map((p) => {
      const o = { count: p.count, drawn: p.drawn, items: p.items.map(r3), size: r3(p.size), loc: p.loc, names: [...p.names] };
      if (p.tools !== undefined) o.tools = p.tools;
      return o;
    }),
    links: w.links.map(([a, b, c]) => [a, b, c]),
  };
}

export function serializeWiring(w) {
  return JSON.stringify(normaliseWiring(w));
}

const WIRING_BEGIN = "// WIRING:BEGIN — generated by `node tools/scan.mjs wire`; do not edit";

/**
 * Replace only the WIRING const (or add the whole block straight after `// PARTS:END`).
 * Every other byte of `source` is kept.
 */
export function writeWiring(source, wiring) {
  const eol = source.includes("\r\n") ? "\r\n" : "\n";
  const line = `const WIRING: Wiring = ${serializeWiring(wiring)};`;
  const block = findBlock(source, "WIRING");
  if (block) {
    const body = source.slice(block.bodyStart, block.bodyEnd);
    const m = /const\s+WIRING\b/.exec(body);
    if (!m) {
      // Marked but empty: put the const on its own line(s) inside the block.
      return source.slice(0, block.bodyStart) + line + eol + source.slice(block.bodyStart);
    }
    const semi = body.lastIndexOf(";");
    const stop = semi >= m.index ? semi + 1 : body.trimEnd().length;
    return source.slice(0, block.bodyStart + m.index) + line + source.slice(block.bodyStart + stop);
  }
  const parts = findBlock(source, "PARTS");
  if (!parts) throw new Error("cannot add the WIRING block: the canvas has no // PARTS:END marker");
  return source.slice(0, parts.end) + eol + WIRING_BEGIN + eol + line + eol + "// WIRING:END" + source.slice(parts.end);
}

/* ─────────────────────────── globs ─────────────────────────── */

function globToRegExp(pattern) {
  let re = "";
  for (let i = 0; i < pattern.length; ) {
    const c = pattern[i];
    if (c === "*") {
      if (pattern[i + 1] === "*") {
        re += ".*";
        while (pattern[i] === "*") i++;
      } else {
        re += "[^/]*";
        i++;
      }
    } else {
      re += c.replace(/[.+?^${}()|[\]\\]/g, "\\$&");
      i++;
    }
  }
  return new RegExp(`^${re}$`, "s");
}

/** Whole-id match. `*` = `[^/]*`, `**` = `.*`. A leading `!` is not special here (see resolvePatterns). */
export function matchGlob(pattern, id) {
  return globToRegExp(pattern).test(id);
}

/**
 * Apply `from` patterns in order: positives add matching ids, `!` patterns remove them.
 * `facts` is a FactsFile, a Fact[] or an id[]. `ids` come back in that list's order;
 * `unmatched` lists positive patterns that matched no fact at all.
 */
export function resolvePatterns(patterns, facts) {
  const list = (Array.isArray(facts) ? facts : (facts?.facts ?? [])).map((f) => (typeof f === "string" ? f : f.id));
  const set = new Set();
  const unmatched = [];
  for (const raw of patterns) {
    const negate = raw.startsWith("!");
    const re = globToRegExp(negate ? raw.slice(1) : raw);
    let hit = false;
    for (const id of list) {
      if (!re.test(id)) continue;
      hit = true;
      if (negate) set.delete(id);
      else set.add(id);
    }
    if (!negate && !hit) unmatched.push(raw);
  }
  return { ids: [...new Set(list)].filter((id) => set.has(id)), unmatched };
}

function levenshtein(a, b) {
  let prev = Array.from({ length: b.length + 1 }, (_, j) => j);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    for (let j = 1; j <= b.length; j++) {
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    }
    prev = cur;
  }
  return prev[b.length];
}

// Up to 3 ids: first those a `**` version of the pattern would match (the usual slip: `*` stops at `/`),
// then the nearest by edit distance (wildcard patterns are compared on their literal prefix).
function suggest(pattern, ids, limit = 3) {
  const out = [];
  if (pattern.includes("*")) {
    const loose = globToRegExp(pattern.replace(/\*+/g, "**"));
    for (const id of ids) if (out.length < limit && loose.test(id)) out.push(id);
  }
  if (out.length < limit) {
    const lit = pattern.includes("*") ? pattern.slice(0, pattern.indexOf("*")) : null;
    const dist = (id) => (lit === null ? levenshtein(pattern, id) : levenshtein(lit, id.slice(0, lit.length + 2)));
    const rest = ids
      .filter((id) => !out.includes(id))
      .map((id) => [dist(id), id])
      .sort((x, y) => x[0] - y[0] || cmp(x[1], y[1]));
    for (const [, id] of rest) if (out.length < limit) out.push(id);
  }
  return out;
}

/* ─────────────────────────── wire ─────────────────────────── */

const parentDir = (d) => (d === "." ? null : d.lastIndexOf("/") < 0 ? "." : d.slice(0, d.lastIndexOf("/")));
const dirOf = (file) => (file.lastIndexOf("/") < 0 ? "." : file.slice(0, file.lastIndexOf("/")));

/**
 * facts + PARTS → WIRING. Pure and deterministic.
 *
 * Returns { wiring, errors, warnings, witnesses, owners, chains }:
 *  - errors / warnings are plain messages (no "✗ " / "! " prefix). With any error, `wiring` is null.
 *  - witnesses: "a-b" (a < b) → one chain per distinct witness. A link's weight is the number of distinct
 *    SOURCE FILES that reach the other part (both directions), so it can be smaller than the witness count.
 *    A chain is [file, …files, file] or [file, …files, factId]; an http hop through an uncited endpoint
 *    reads [file, endpointId, endpointFile].
 *  - owners: file → index of the part that owns it.
 *  - chains: "a-b" → [{ from, chain }] for every walk direction (used by `why`).
 */
export function wire(facts, parts) {
  const errors = [];
  const warnings = [];
  const bail = () => ({ wiring: null, errors, warnings, witnesses: new Map(), owners: new Map(), chains: new Map() });

  if (!Array.isArray(parts)) {
    errors.push("PARTS must be an array");
    return bail();
  }
  const factList = Array.isArray(facts?.facts) ? facts.facts : [];
  const files = facts?.files ?? {};
  const factById = new Map(factList.map((f) => [f.id, f]));
  const allIds = factList.map((f) => f.id).sort(cmp);

  /* 1. shape, count, names */
  const count = parts.length;
  if (count < MIN_PARTS || count > MAX_PARTS) errors.push(`${count} parts — use 2 to 9`);
  else if (count === MIN_PARTS) warnings.push("2 parts — three or more make a richer drawing");

  const valid = parts.map((p, i) => {
    if (!p || typeof p !== "object") {
      errors.push(`Part ${i + 1} must be an object with name, role, line and from`);
      return false;
    }
    let ok = true;
    const named = typeof p.name === "string" && p.name.trim() !== "";
    const who = named ? `"${p.name}"` : String(i + 1);
    if (!named) {
      errors.push(`Part ${i + 1} has no "name"`);
      ok = false;
    } else if (charLen(p.name) > MAX_NAME_LEN) {
      errors.push(`Part name "${p.name}" is ${charLen(p.name)} characters — ${MAX_NAME_LEN} at most`);
    }
    if (!ROLES.includes(p.role)) {
      errors.push(`Part ${who}: role ${JSON.stringify(p.role)} is not one of ${ROLES.join(", ")}`);
      ok = false;
    }
    if (p.detail !== undefined && (typeof p.detail !== "string" || p.detail.trim() === "" || charLen(p.detail) > MAX_DETAIL_LEN)) {
      errors.push(`Part ${who}: detail must be a sentence of ${MAX_DETAIL_LEN} characters at most`);
    }
    if (!Array.isArray(p.from) || p.from.length === 0 || p.from.some((s) => typeof s !== "string" || s === "")) {
      errors.push(`Part ${who}: "from" must be a non-empty array of id patterns`);
      ok = false;
    }
    return ok;
  });

  /* 2. resolve patterns, check kinds */
  const citedIds = parts.map(() => []); // per part: allowed ids (role kind + area), sorted
  const patternError = parts.map(() => false); // a part that already has a pattern error skips "counts nothing"
  parts.forEach((p, i) => {
    if (!valid[i]) return;
    const { ids, unmatched } = resolvePatterns(p.from, factList);
    for (const pat of unmatched) {
      patternError[i] = true;
      const near = suggest(pat, allIds);
      errors.push(`Part "${p.name}": "${pat}" matches nothing${near.length ? ` — did you mean ${near.join(", ")}?` : ""}`);
    }
    const want = ROLE_KIND[p.role];
    const positives = p.from.filter((s) => !s.startsWith("!")).map((s) => [s, globToRegExp(s)]);
    const bad = new Map();
    for (const id of ids) {
      const kind = factById.get(id).kind;
      if (kind === want || kind === "area") {
        citedIds[i].push(id);
        continue;
      }
      const pat = positives.find(([, re]) => re.test(id))?.[0] ?? id;
      bad.set(`${pat}\0${kind}`, { pat, kind });
    }
    for (const { pat, kind } of bad.values()) {
      patternError[i] = true;
      errors.push(`Part "${p.name}": "${pat}" matches ${kind} facts — a ${p.role} part counts only ${want} (plus area: for ownership)`);
    }
    citedIds[i].sort(cmp);
  });

  /* 3. no double citations */
  const citedBy = new Map(); // id → part indexes (ascending), every kind
  citedIds.forEach((ids, i) => {
    for (const id of ids) {
      const l = citedBy.get(id);
      if (l) l.push(i);
      else citedBy.set(id, [i]);
    }
  });
  for (const [id, who] of citedBy) {
    for (let k = 1; k < who.length; k++) errors.push(`${id} is cited by both "${parts[who[0]].name}" and "${parts[who[k]].name}"`);
  }

  /* 4. what each part counts */
  const areaByDir = new Map();
  for (const f of factList) if (f.kind === "area") areaByDir.set(f.id.slice(5), f);
  const areaLoc = (f) => {
    if (typeof f.loc === "number") return f.loc;
    const dir = f.id.slice(5);
    let sum = 0;
    for (const [file, info] of Object.entries(files)) if (!info.gen && (dir === "." || file.startsWith(`${dir}/`))) sum += info.loc ?? 0;
    return sum;
  };
  // Feature chips. One cited area → its direct child areas (minus those the part removes with `!area:…`)
  // plus one chip, named after the area, for its own files outside all its children (if they have LOC).
  // Several cited areas → those areas. A single area that yields no chip at all is one chip itself.
  const featureChips = (areaIds, from) => {
    const cited = areaIds.map((id) => factById.get(id));
    let chips;
    if (cited.length === 1) {
      const top = cited[0];
      const topDir = top.id.slice(5);
      const kids = factList.filter((f) => {
        if (f.kind !== "area" || f.id === top.id) return false;
        let d = parentDir(f.id.slice(5));
        while (d !== null && !areaByDir.has(d)) d = parentDir(d);
        return d === topDir;
      });
      const removed = from.filter((s) => s.startsWith("!")).map((s) => globToRegExp(s.slice(1)));
      chips = kids.filter((k) => !removed.some((re) => re.test(k.id))).map((k) => ({ name: k.name ?? k.id, loc: areaLoc(k) }));
      const own = areaLoc(top) - kids.reduce((sum, k) => sum + areaLoc(k), 0);
      if (own > 0) chips.push({ name: top.name ?? top.id, loc: own });
      if (chips.length === 0) chips.push({ name: top.name ?? top.id, loc: areaLoc(top) });
    } else {
      chips = cited.map((f) => ({ name: f.name ?? f.id, loc: areaLoc(f) }));
    }
    chips.sort((a, b) => b.loc - a.loc || cmp(a.name, b.name));
    const total = chips.reduce((sum, c) => sum + c.loc, 0);
    return chips.map((c) => ({ name: c.name, w: total > 0 ? c.loc / total : 1 }));
  };

  const listed = parts.map((p, i) => {
    if (!valid[i]) return null;
    const ids = citedIds[i];
    let list;
    if (p.role === "feature") {
      list = featureChips(ids.filter((id) => factById.get(id).kind === "area"), p.from);
    } else {
      list = ids.filter((id) => factById.get(id).kind !== "area").map((id) => ({ name: factById.get(id).name ?? id, w: 1 }));
    }
    if (list.length === 0 && !patternError[i]) errors.push(`${p.role} part "${p.name}" counts nothing`);
    return list;
  });

  if (errors.length) return bail();

  /* 5. ownership (§3.2) */
  const fileNames = Object.keys(files).sort(cmp);
  const owners = new Map();
  // rule 1: defines a cited screen / endpoint / table / job
  const defining = new Map(); // file → Map(part → number of cited defining facts)
  parts.forEach((_, i) => {
    for (const id of citedIds[i]) {
      const f = factById.get(id);
      if (!DEFINING_KINDS.has(f.kind)) continue;
      for (const file of f.files ?? []) {
        if (!files[file]) continue;
        let m = defining.get(file);
        if (!m) defining.set(file, (m = new Map()));
        m.set(i, (m.get(i) ?? 0) + 1);
      }
    }
  });
  for (const [file, m] of defining) {
    let best = -1;
    let bestN = 0;
    for (const [i, n] of [...m].sort((a, b) => a[0] - b[0])) {
      if (n > bestN) {
        best = i;
        bestN = n;
      }
    }
    owners.set(file, best);
  }
  // rule 2: deepest cited area directory
  const areaOwner = new Map(); // dir → part
  parts.forEach((_, i) => {
    for (const id of citedIds[i]) if (id.startsWith("area:")) areaOwner.set(id.slice(5), i);
  });
  if (areaOwner.size) {
    for (const file of fileNames) {
      if (owners.has(file)) continue;
      for (let d = dirOf(file); d !== null; d = parentDir(d)) {
        if (areaOwner.has(d)) {
          owners.set(file, areaOwner.get(d));
          break;
        }
      }
    }
  }
  // rule 3: data file, when there is exactly one data part
  const dataParts = parts.flatMap((p, i) => (p.role === "data" ? [i] : []));
  if (dataParts.length === 1) {
    for (const file of fileNames) if (files[file].data && !owners.has(file)) owners.set(file, dataParts[0]);
  }

  /* 6. sizes */
  let totalLoc = 0;
  const ownedLoc = parts.map(() => 0);
  for (const file of fileNames) {
    const info = files[file];
    if (info.gen) continue;
    const loc = info.loc ?? 0;
    totalLoc += loc;
    if (owners.has(file)) ownedLoc[owners.get(file)] += loc;
  }

  /* 7. links (§3.3) */
  const importsOut = new Map();
  for (const [a, b] of facts.imports ?? []) {
    if (!files[a] || !files[b]) continue;
    const l = importsOut.get(a);
    if (l) l.push(b);
    else importsOut.set(a, [b]);
  }
  const usesOf = new Map();
  for (const [file, id] of facts.uses ?? []) {
    if (!files[file]) continue;
    const l = usesOf.get(file);
    if (l) l.push(id);
    else usesOf.set(file, [id]);
  }
  const httpOf = new Map(); // file → [endpoint ids it calls]
  for (const [file, id, via] of facts.uses ?? []) {
    if (via !== "http" || !files[file]) continue;
    const l = httpOf.get(file);
    if (l) l.push(id);
    else httpOf.set(file, [id]);
  }
  for (const l of usesOf.values()) l.sort(cmp);
  const neighbourCache = new Map();
  // Sorted [file, viaEndpointId | undefined]: imports, plus http calls to uncited endpoints followed to their files.
  const neighboursOf = (file) => {
    let c = neighbourCache.get(file);
    if (c) return c;
    const m = new Map();
    for (const to of importsOut.get(file) ?? []) if (!m.has(to)) m.set(to, undefined);
    for (const id of [...(httpOf.get(file) ?? [])].sort(cmp)) {
      const ep = factById.get(id);
      if (!ep || ep.kind !== "endpoint" || citedBy.has(id)) continue;
      for (const to of ep.files ?? []) if (files[to] && !m.has(to)) m.set(to, id);
    }
    c = [...m].sort((x, y) => cmp(x[0], y[0]));
    neighbourCache.set(file, c);
    return c;
  };

  const pairs = new Map(); // "a-b" → { sources: Set(file), distinct: Map(key → chain), directed: Map(key → {from, chain}) }
  const chainTo = (parent, node) => {
    const out = [];
    for (let cur = node; ; ) {
      out.push(cur);
      const e = parent.get(cur);
      if (!e) break;
      if (e.via) out.push(e.via);
      cur = e.prev;
    }
    return out.reverse();
  };
  const addWitness = (p, q, source, other, makeChain) => {
    const a = Math.min(p, q);
    const b = Math.max(p, q);
    const pk = `${a}-${b}`;
    let rec = pairs.get(pk);
    if (!rec) pairs.set(pk, (rec = { sources: new Set(), distinct: new Map(), directed: new Map() }));
    rec.sources.add(source); // weight counts source files, not witnesses
    const uk = p < q ? `${source}\0${other}` : `${other}\0${source}`; // lower part's end first: (f,g) and (g,f) are one wire
    const dk = `${p}\0${source}\0${other}`;
    const newDistinct = !rec.distinct.has(uk);
    if (!newDistinct && rec.directed.has(dk)) return;
    const chain = makeChain();
    if (newDistinct) rec.distinct.set(uk, chain);
    if (!rec.directed.has(dk)) rec.directed.set(dk, { from: p, chain });
  };

  for (const f of fileNames) {
    const p = owners.get(f);
    if (p === undefined || files[f].kit) continue;
    const parent = new Map([[f, null]]);
    const examineUses = (u) => {
      for (const id of usesOf.get(u) ?? []) {
        const q = citedBy.get(id)?.[0];
        if (q === undefined || q === p || factById.get(id).kind === "area") continue;
        addWitness(p, q, f, id, () => [...chainTo(parent, u), id]);
      }
    };
    examineUses(f);
    let frontier = [f];
    for (let hop = 1; hop <= MAX_HOPS && frontier.length; hop++) {
      const next = [];
      for (const cur of frontier) {
        for (const [to, via] of neighboursOf(cur)) {
          if (parent.has(to)) continue;
          const info = files[to];
          if (!info || info.kit) continue;
          parent.set(to, { prev: cur, via });
          const q = owners.get(to);
          if (q !== undefined) {
            if (q !== p) addWitness(p, q, f, to, () => chainTo(parent, to));
            continue; // stop at the first owned file on this branch
          }
          examineUses(to);
          if (hop < MAX_HOPS) next.push(to);
        }
      }
      frontier = next;
    }
  }

  const links = [];
  const witnesses = new Map();
  const chains = new Map();
  for (const [key, rec] of pairs) {
    const [a, b] = key.split("-").map(Number);
    links.push([a, b, rec.sources.size]);
    witnesses.set(key, [...rec.distinct.values()]);
    chains.set(key, [...rec.directed.values()]);
  }
  links.sort((x, y) => x[0] - y[0] || x[1] - y[1]);

  /* 8. counts → WIRING.n */
  const n = parts.map((p, i) => {
    const list = listed[i];
    const cap = CAPS[p.role];
    const drawn = Math.min(list.length, cap);
    const items = list.slice(0, drawn).map((c) => c.w);
    if (list.length > cap) items[cap - 1] = 1; // the last drawn item is the bundle
    const out = {
      count: list.length,
      drawn,
      items,
      size: totalLoc > 0 ? ownedLoc[i] / totalLoc : 0,
      loc: ownedLoc[i],
      names: [...new Set(list.map((c) => c.name))].slice(0, MAX_NAMES), // de-duplicated, first occurrence kept
    };
    if (p.role === "ai") {
      out.tools = citedIds[i].reduce((s, id) => s + (factById.get(id).kind === "ai" ? (factById.get(id).meta?.tools ?? 0) : 0), 0);
    }
    return out;
  });

  /* 9. warnings */
  const linked = new Set(links.flatMap(([a, b]) => [a, b]));
  parts.forEach((p, i) => {
    if (!linked.has(i)) warnings.push(`"${p.name}" has no links`);
  });
  const uncited = { service: [], ai: [], job: [], table: [], screen: [] };
  for (const f of factList) if (uncited[f.kind] && !citedBy.has(f.id)) uncited[f.kind].push(f);
  const notDrawn = [];
  const listNames = (kind, label, plural2) => {
    const l = uncited[kind];
    if (l.length === 0) return;
    if (l.length <= 3) for (const f of l) notDrawn.push(`${f.name ?? f.id} (${label})`);
    else notDrawn.push(`${l.length} ${plural2}`);
  };
  listNames("service", "service", "services");
  listNames("ai", "AI", "AI providers");
  if (uncited.job.length) notDrawn.push(plural(uncited.job.length, "job"));
  if (uncited.table.length) notDrawn.push(plural(uncited.table.length, "table"));
  if (uncited.screen.length) notDrawn.push(plural(uncited.screen.length, "screen"));
  if (notDrawn.length) warnings.push(`Not drawn: ${notDrawn.join(", ")}`);

  const wiring = normaliseWiring({ facts: facts.hash ?? factsHash(facts), parts: partsHash(parts), n, links });
  return { wiring, errors, warnings, witnesses, owners, chains };
}

/* ─────────────────────────── CLI ─────────────────────────── */

const defaultIo = () => ({
  out: (s) => process.stdout.write(`${s}\n`),
  err: (s) => process.stderr.write(`${s}\n`),
});

// Tiny flag parser: `--name value` or `--name=value`; everything else is positional.
function parseArgs(args, valueFlags) {
  const positional = [];
  const flags = {};
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a.startsWith("--")) {
      const eq = a.indexOf("=");
      const name = eq < 0 ? a.slice(2) : a.slice(2, eq);
      if (!valueFlags.includes(name)) return { error: `unknown option --${name}` };
      const value = eq < 0 ? args[++i] : a.slice(eq + 1);
      if (value === undefined || value === "") return { error: `--${name} needs a value` };
      flags[name] = value;
    } else positional.push(a);
  }
  return { positional, flags };
}

function readText(file, io) {
  try {
    return fs.readFileSync(path.resolve(file), "utf8");
  } catch (e) {
    io.err(`✗ cannot read ${file}: ${e.code ?? e.message}`);
    return null;
  }
}

function loadFacts(file, io) {
  const text = readText(file, io);
  if (text === null) return null;
  let facts;
  try {
    facts = JSON.parse(text);
  } catch (e) {
    io.err(`✗ ${file} is not valid JSON: ${e.message}`);
    return null;
  }
  if (!facts || typeof facts !== "object" || facts.version !== 1 || !Array.isArray(facts.facts)) {
    io.err(`✗ ${file} is not a facts.json (version 1) — re-run scan`);
    return null;
  }
  if (factsHash(facts) !== facts.hash) {
    io.err("✗ facts.json hash does not recompute — re-run scan");
    return null;
  }
  return facts;
}

function loadParts(canvasFile, io) {
  const source = readText(canvasFile, io);
  if (source === null) return null;
  let blocks;
  try {
    blocks = readBlocks(source);
  } catch (e) {
    io.err(`✗ ${e.message}`);
    return null;
  }
  if (!blocks.parts) {
    io.err(`✗ ${canvasFile} has no // PARTS:BEGIN … // PARTS:END block`);
    return null;
  }
  return { source, parts: blocks.parts };
}

function report(result, io) {
  for (const e of result.errors) io.err(`✗ ${e}`);
  for (const w of result.warnings) io.err(`! ${w}`);
}

/** `wire <facts.json> --into <canvas.tsx>`: rewrite the WIRING block. Exit 0 ok, 1 rule error, 2 usage. */
export async function wireMain(argv, io = defaultIo()) {
  const args = argv[0] === "wire" ? argv.slice(1) : argv;
  const parsed = parseArgs(args, ["into"]);
  if (parsed.error || parsed.positional.length !== 1 || !parsed.flags.into) {
    if (parsed.error) io.err(`✗ ${parsed.error}`);
    io.err("usage: node tools/scan.mjs wire <facts.json> --into <canvas.tsx>");
    return 2;
  }
  const facts = loadFacts(parsed.positional[0], io);
  if (!facts) return 1;
  const canvas = loadParts(parsed.flags.into, io);
  if (!canvas) return 1;

  const result = wire(facts, canvas.parts);
  report(result, io);
  if (result.errors.length) return 1;

  const next = writeWiring(canvas.source, result.wiring);
  if (next !== canvas.source) fs.writeFileSync(path.resolve(parsed.flags.into), next);
  const weight = result.wiring.links.reduce((s, l) => s + l[2], 0);
  io.out(`wired ${plural(canvas.parts.length, "part")}, ${plural(result.wiring.links.length, "link")}, total weight ${weight}`);
  return 0;
}

function findPart(parts, key) {
  const k = key.trim().toLowerCase();
  const byName = parts.map((p, i) => [p.name?.toLowerCase(), i]).filter(([n]) => n === k);
  if (byName.length === 1) return byName[0][1];
  if (/^\d+$/.test(k) && Number(k) < parts.length) return Number(k);
  const partial = parts.map((p, i) => [p.name?.toLowerCase() ?? "", i]).filter(([n]) => n.includes(k));
  return partial.length === 1 ? partial[0][1] : -1;
}

// "file → file", "file ─uses→ factId", "factId → file" (an http hop through an uncited endpoint).
function formatChain(chain, files) {
  const isFile = (s) => Object.hasOwn(files, s);
  return chain
    .map((el, i) => {
      if (i === 0) return el;
      return `${!isFile(el) ? " ─uses→ " : " → "}${el}`;
    })
    .join("");
}

/** `why <facts.json> --canvas <canvas.tsx> "<part A>" "<part B>"`: show the shortest wire each way. */
export async function whyMain(argv, io = defaultIo()) {
  const args = argv[0] === "why" ? argv.slice(1) : argv;
  const parsed = parseArgs(args, ["canvas"]);
  if (parsed.error || parsed.positional.length !== 3 || !parsed.flags.canvas) {
    if (parsed.error) io.err(`✗ ${parsed.error}`);
    io.err('usage: node tools/scan.mjs why <facts.json> --canvas <canvas.tsx> "<part A>" "<part B>"  (a part is a name or a 0-based index)');
    return 2;
  }
  const [factsFile, keyA, keyB] = parsed.positional;
  const facts = loadFacts(factsFile, io);
  if (!facts) return 1;
  const canvas = loadParts(parsed.flags.canvas, io);
  if (!canvas) return 1;
  const result = wire(facts, canvas.parts);
  report(result, io);
  if (result.errors.length) return 1;

  const ia = findPart(canvas.parts, keyA);
  const ib = findPart(canvas.parts, keyB);
  const names = canvas.parts.map((p, i) => `${i}: ${p.name}`).join("; ");
  for (const [key, i] of [[keyA, ia], [keyB, ib]]) {
    if (i < 0) {
      io.err(`✗ no part matches "${key}" — parts are ${names}`);
      return 2;
    }
  }
  if (ia === ib) {
    io.err("✗ pick two different parts");
    return 2;
  }
  const nameA = canvas.parts[ia].name;
  const nameB = canvas.parts[ib].name;
  const pair = `${Math.min(ia, ib)}-${Math.max(ia, ib)}`;
  const recs = result.chains.get(pair) ?? [];
  if (recs.length === 0) {
    io.out(`No wire between ${nameA} and ${nameB}`);
    return 0;
  }
  const weight = result.wiring.links.find((l) => l[0] === Math.min(ia, ib) && l[1] === Math.max(ia, ib))?.[2] ?? 0;
  io.out(`${nameA} ↔ ${nameB} (weight ${weight})`);
  for (const [from, to] of [[ia, ib], [ib, ia]]) {
    const best = recs
      .filter((r) => r.from === from)
      .sort((x, y) => x.chain.length - y.chain.length || cmp(x.chain.join("\0"), y.chain.join("\0")))[0];
    if (best) io.out(`${canvas.parts[from].name} → ${canvas.parts[to].name}: ${formatChain(best.chain, facts.files)}`);
  }
  return 0;
}
