// File listing, exclusion rules, reading, LOC and generated-file detection (CONTRACTS §2.2).
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { basename, cmp, countLoc, dirname, extname } from "./util.mjs";

export const SOURCE_EXT = new Set([
  ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".mts", ".cts", ".vue", ".svelte", ".astro",
  ".py", ".go", ".rb", ".rs", ".php", ".java", ".kt", ".swift", ".sql", ".prisma", ".mdx",
]);
// Files whose `import` lines are parsed JS-style. .mdx is content, but its ESM blocks are code.
export const JS_EXT = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".mts", ".cts", ".vue", ".svelte", ".astro", ".mdx"]);

export const MAX_BYTES = 512 * 1024;
export const MAX_FILES = 20000;

const EXCLUDED_DIRS = new Set([
  "node_modules", ".git", "dist", "build", "out", ".next", ".nuxt", ".svelte-kit", ".turbo", ".vercel",
  "coverage", "vendor", "venv", ".venv", "__pycache__", "site-packages", "bower_components",
  "__tests__", "tests", "test", "e2e", "cypress", "playwright", "public", "static", "assets",
]);

// Skipped while walking / listing: these directories never hold anything we read.
const NEVER_WALK = new Set(["node_modules", ".git", "__pycache__", "site-packages", "bower_components", ".venv", "venv", ".next", ".nuxt", ".svelte-kit", ".turbo", ".vercel"]);

// True when a repo-relative path is outside the "kept source files" set.
export function isExcluded(rel) {
  const segs = rel.split("/");
  const file = segs[segs.length - 1];
  for (let i = 0; i < segs.length - 1; i++) {
    const s = segs[i];
    if (EXCLUDED_DIRS.has(s) || s.startsWith(".")) return true;
  }
  if (file.startsWith(".")) return true;
  if (/\.(test|spec)\.[^/]+$/.test(file)) return true;
  if (/\.config\.[^/]+$/.test(file)) return true;
  if (/\.d\.[cm]?ts$/.test(file)) return true;
  if (/^(test_.*|.*_test)\.py$/.test(file) || file === "conftest.py" || /_test\.go$/.test(file)) return true;
  return false;
}

export function isSourcePath(rel) {
  return SOURCE_EXT.has(extname(rel)) && !isExcluded(rel);
}

// How every git call here is made, so a caller can spawn git the same way: `git <GIT_FLAGS> -C <dir> …` with
// `env: gitEnv()`. No fsmonitor daemon, no hooks, no optional index refresh, so reading never writes into .git.
export const GIT_FLAGS = ["-c", "core.fsmonitor=false", "-c", "core.hooksPath=/dev/null"];
export const gitEnv = () => ({ ...process.env, GIT_OPTIONAL_LOCKS: "0" });

/** Run git in `dir` and return stdout as text. Throws when git is missing or the command fails. */
export function gitOutput(dir, args) {
  return execFileSync("git", [...GIT_FLAGS, "-C", dir, ...args], {
    encoding: "utf8",
    maxBuffer: 512 * 1024 * 1024,
    stdio: ["ignore", "pipe", "ignore"],
    env: gitEnv(),
  });
}

const nulList = (raw) => raw.split("\0").filter(Boolean);

// List every file in the repo (unfiltered), sorted. Uses git when `dir` is a work-tree root, else walks.
// In git mode the listing is what is on disk now: tracked files minus those deleted without staging
// (`ls-files -d`), plus untracked files that are not ignored.
export function listFiles(dir, { useGit = true } = {}) {
  if (useGit) {
    try {
      const prefix = gitOutput(dir, ["rev-parse", "--show-prefix"]).trim();
      const inside = gitOutput(dir, ["rev-parse", "--is-inside-work-tree"]).trim() === "true";
      if (inside && prefix === "") {
        const listed = nulList(gitOutput(dir, ["ls-files", "-co", "--exclude-standard", "-z"]));
        const gone = new Set(nulList(gitOutput(dir, ["ls-files", "-d", "-z"])));
        return { paths: [...new Set(listed.filter((p) => !gone.has(p)))].sort(cmp), git: true };
      }
    } catch {
      // not a git work tree (or git unavailable): fall through to the walk
    }
  }
  const paths = [];
  const walk = (rel) => {
    let entries;
    try {
      entries = fs.readdirSync(path.join(dir, rel), { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      if (e.isSymbolicLink()) continue;
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) {
        if (NEVER_WALK.has(e.name)) continue;
        walk(r);
      } else if (e.isFile()) paths.push(r);
    }
  };
  walk("");
  return { paths: paths.sort(cmp), git: false };
}

const GEN_DIR = /(^|\/)(__generated__|generated|\.generated)(\/|$)/;
const MIGRATION_DIR = /(^|\/)(migrations|migration|alembic\/versions)(\/|$)/;
const GEN_NAME = /(\.gen\.|\.generated\.|\.pb\.|_pb2?(_grpc)?\.|\.g\.dart$|routeTree\.gen)/;
const GEN_HEAD = /@generated|auto-?generated|automatically generated|do not edit|do not modify|generated by|code generated|this file was generated|generated file|autogenerated/i;

// Generated files keep their place in `files` but never count toward LOC or kit detection.
export function detectGen(rel, text) {
  if (GEN_NAME.test(basename(rel)) || GEN_DIR.test(dirname(rel) + "/") || MIGRATION_DIR.test(dirname(rel) + "/")) return true;
  if (rel.endsWith(".mdx")) return false; // prose: markdown headings start with "#", paragraphs are long lines
  const head = text
    .slice(0, 700)
    .split("\n")
    .slice(0, 10)
    .filter((l) => /^\s*(\/\/|\/\*|\*|#|--|<!--|"""|')/.test(l))
    .join("\n");
  if (GEN_HEAD.test(head)) return true;
  // a minified bundle: a huge line, or very long lines on average
  let longest = 0;
  let run = 0;
  let lines = 1;
  const lim = Math.min(text.length, 200000);
  for (let i = 0; i < lim; i++) {
    if (text.charCodeAt(i) === 10) {
      if (run > longest) longest = run;
      run = 0;
      lines++;
    } else run++;
  }
  if (run > longest) longest = run;
  return longest > 20000 || (lim > 8000 && lim / lines > 400);
}

// Read the kept source files. Skips files over MAX_BYTES, binary files and anything unreadable.
// Returns { files: Map<rel,{text,loc,gen}>, skipped: {big,binary,unreadable,capped} }.
export function readSourceFiles(dir, paths) {
  const skipped = { big: 0, binary: 0, unreadable: 0, capped: 0 };
  let candidates = paths.filter(isSourcePath);
  if (candidates.length > MAX_FILES) {
    skipped.capped = candidates.length - MAX_FILES;
    candidates = candidates
      .map((p) => [p, p.split("/").length])
      .sort((a, b) => a[1] - b[1] || cmp(a[0], b[0]))
      .slice(0, MAX_FILES)
      .map((x) => x[0])
      .sort(cmp);
  }
  const files = new Map();
  for (const rel of candidates) {
    const abs = path.join(dir, rel);
    try {
      const st = fs.lstatSync(abs);
      if (!st.isFile()) continue;
      if (st.size > MAX_BYTES) {
        skipped.big++;
        continue;
      }
      const buf = fs.readFileSync(abs);
      if (buf.subarray(0, 8000).includes(0)) {
        skipped.binary++;
        continue;
      }
      const text = buf.toString("utf8");
      files.set(rel, { text, loc: countLoc(text), gen: detectGen(rel, text) });
    } catch {
      skipped.unreadable++;
    }
  }
  return { files, skipped };
}

// Read a small non-source file (package.json, tsconfig.json, vercel.json, …). null when missing/unreadable.
export function readSmall(dir, rel) {
  try {
    const abs = path.join(dir, rel);
    const st = fs.lstatSync(abs);
    if (!st.isFile() || st.size > 2 * 1024 * 1024) return null;
    return fs.readFileSync(abs, "utf8");
  } catch {
    return null;
  }
}
